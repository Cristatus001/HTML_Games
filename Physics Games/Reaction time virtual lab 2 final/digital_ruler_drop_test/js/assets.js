/* ============================================================
   assets.js — optional drop-in art with graceful fallback.

   Every visual element that CAN be replaced by a bitmap declares a
   slot here. On boot we probe each path; if the file exists the game
   swaps it in, and if it is missing the built-in CSS/SVG art is kept.
   Nothing throws and nothing blocks: a completely empty
   assets/images tree renders the full game.

   Drop-in filenames and sizes are documented in
   assets/images/README.md.
   ============================================================ */
(function (global) {
  'use strict';

  var IMG_BASE = 'assets/images/';

  /* slot id -> { path, apply(img) }
     `apply` runs only when the image actually decodes. */
  var SLOTS = {
    /* --- apparatus --- */
    ruler: {
      path: 'apparatus/ruler.png',
      apply: function (img) {
        var el = document.getElementById('ruler-img');
        var face = document.getElementById('ruler');
        if (!el || !face) return;
        el.src = img.src;
        el.hidden = false;
        /* keep the engraved ticks on top of custom art unless the art
           declares its own scale by being tagged in the README */
        face.classList.add('has-art');
      }
    },
    dropperHand: {
      path: 'characters/hand_dropper.png',
      apply: function (img) { swapHand('dropper-hand', img); }
    },
    catcherHand: {
      path: 'characters/hand_catcher.png',
      apply: function (img) { swapHand('catcher-hand', img); }
    },

    /* --- background --- */
    backdrop: {
      path: 'background/lab_backdrop.png',
      apply: function (img) {
        var bg = document.getElementById('stage-bg');
        if (!bg) return;
        bg.style.backgroundImage = 'url("' + img.src + '")';
        bg.style.backgroundSize = 'cover';
        bg.style.backgroundPosition = 'center';
        bg.classList.add('has-backdrop');
      }
    },
    benchTexture: {
      path: 'background/bench_texture.png',
      apply: function (img) {
        var el = document.querySelector('.bench-base');
        if (!el) return;
        el.style.backgroundImage = 'url("' + img.src + '")';
        el.style.backgroundSize = 'auto 100%';
        el.style.backgroundRepeat = 'repeat-x';
      }
    },

    /* --- UI --- */
    panelSkin: {
      path: 'ui/panel_skin.png',
      apply: function (img) {
        document.documentElement.style.setProperty(
          '--panel-skin', 'url("' + img.src + '")');
        document.body.classList.add('has-panel-skin');
      }
    },
    titleLogo: {
      path: 'ui/title_logo.png',
      apply: function (img) {
        var title = document.querySelector('.game-title');
        var crest = document.querySelector('.title-crest');
        if (!title) return;
        var logo = document.createElement('img');
        logo.src = img.src;
        logo.alt = 'Digital Ruler Drop Test';
        logo.className = 'title-logo-img';
        logo.style.maxHeight = 'min(26vh,180px)';
        logo.style.width = 'auto';
        title.replaceWith(logo);
        if (crest) crest.hidden = true;
      }
    }
  };

  function swapHand(hostId, img) {
    var host = document.getElementById(hostId);
    if (!host) return;
    var svg = host.querySelector('.hand-svg');
    var slot = host.querySelector('.hand-img');
    if (!slot) return;
    slot.src = img.src;
    slot.hidden = false;
    if (svg) svg.style.display = 'none';
    host.classList.add('has-art');
  }

  /* --- icons: always present, generated by tools/gen_icons.mjs --- */
  var ICON_BASE = IMG_BASE + 'ui/emoji/';
  function icon(name) { return ICON_BASE + name + '.png'; }

  /** Swap an <img> icon's src by logical name (never emoji textContent). */
  function setIcon(elOrId, name) {
    var el = typeof elOrId === 'string' ? document.getElementById(elOrId) : elOrId;
    if (!el) return;
    var next = icon(name);
    /* avoid a redundant reload / flicker */
    if (el.getAttribute('src') !== next) el.setAttribute('src', next);
  }

  /** Probe one image. Resolves true if it loaded, false otherwise. */
  function probe(path) {
    return new Promise(function (resolve) {
      var img = new Image();
      var done = false;
      function finish(ok) {
        if (done) return;
        done = true;
        resolve(ok ? img : null);
      }
      img.onload = function () {
        finish(img.naturalWidth > 0 && img.naturalHeight > 0);
      };
      img.onerror = function () { finish(false); };
      /* a stalled decode must never hold up the boot sequence */
      setTimeout(function () { finish(false); }, 4000);
      img.src = IMG_BASE + path;
    });
  }

  var loaded = Object.create(null);

  /** Probe every optional slot; apply the ones that exist. */
  function loadOptional() {
    var names = Object.keys(SLOTS);
    return Promise.all(names.map(function (name) {
      var slot = SLOTS[name];
      return probe(slot.path).then(function (img) {
        if (!img) { loaded[name] = false; return; }
        loaded[name] = true;
        try {
          slot.apply(img);
        } catch (err) {
          /* a bad drop-in must not break the game */
          loaded[name] = false;
          if (global.console) console.warn('asset slot "' + name + '" failed to apply:', err);
        }
      });
    })).then(function () { return loaded; });
  }

  /** Warm the icon cache so first paint of a screen has no pop-in. */
  function preloadIcons(names) {
    names.forEach(function (n) { var i = new Image(); i.src = icon(n); });
  }

  global.Assets = {
    icon: icon,
    setIcon: setIcon,
    loadOptional: loadOptional,
    preloadIcons: preloadIcons,
    has: function (name) { return !!loaded[name]; }
  };
})(window);
